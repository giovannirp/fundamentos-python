# Tupla contendo outras tuplas
alunos = (
    ("Carlos", 17),
    ("Ana", 18),
    ("João", 16)
)

# Acessando a primeira tupla
print(alunos[0])       # ('Carlos', 17)

# Acessando o nome do primeiro aluno
print(alunos[0][0])    # Carlos

# Acessando a idade do primeiro aluno
print(alunos[0][1])    # 17